// money-golden.mjs - the Money engine's answers, from the JavaScript engine itself, so the
// Rust port can be held to them exactly.
//
//   node rust/tools/money-golden.mjs extract   copy the bank fixtures out of money.selftest.mjs
//   node rust/tools/money-golden.mjs golden    write tests/golden.json from app/src/money/*.mjs
//   node rust/tools/money-golden.mjs parse <in.jsonl> <out.jsonl>
//        parse every statement text in a JSON-lines file (the differential fuzz run)
//
// Developer tool. Reads and writes only under rust/crates/hideout-money/tests and the paths
// it is given.
import fs from "node:fs";
import path from "node:path";
import readline from "node:readline";
import { fileURLToPath } from "node:url";
import { parseStatement, parseAmount, parseDate, maskDigits, classify } from "../../app/src/money/statement.mjs";
import { analyze } from "../../app/src/money/analyze.mjs";
import { prepareMerchants, loadMerchants, safeCancelUrl, matchMerchant, merchantKey } from "../../app/src/money/directory.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const FIX = path.join(HERE, "..", "crates", "hideout-money", "tests", "fixtures");
const GOLDEN = path.join(HERE, "..", "crates", "hideout-money", "tests", "golden.json");
const FILES = [["CHASE_CARD", "chase.csv"], ["AMEX", "amex.csv"], ["CAPONE", "capone.csv"], ["BOFA", "bofa.csv"], ["WELLS", "wells.csv"]];

const mode = process.argv[2];

if (mode === "extract") {
  const src = fs.readFileSync(path.join(HERE, "..", "..", "app", "tests", "money.selftest.mjs"), "utf8");
  fs.mkdirSync(FIX, { recursive: true });
  for (const [name, file] of FILES) {
    const start = src.indexOf(`const ${name} = \``);
    const end = src.indexOf("`;", start);
    fs.writeFileSync(path.join(FIX, file), src.slice(start + `const ${name} = \``.length, end));
  }
  const d0 = src.indexOf("const DIR = prepareMerchants(");
  const d1 = src.indexOf("\n]);", d0);
  const dir = Function(`return ${src.slice(d0 + "const DIR = prepareMerchants(".length, d1 + 2)};`)();
  fs.writeFileSync(path.join(FIX, "dir.json"), JSON.stringify(dir, null, 1));
  console.log("extracted", fs.readdirSync(FIX).join(", "));
} else if (mode === "golden") {
  const texts = Object.fromEntries(FILES.map(([, f]) => [f, fs.readFileSync(path.join(FIX, f), "utf8")]));
  const DIR = prepareMerchants(JSON.parse(fs.readFileSync(path.join(FIX, "dir.json"), "utf8")));
  const strip = (dir) => dir; // _patterns are not compared
  const parsed = Object.fromEntries(Object.entries(texts).map(([f, t]) => [f, parseStatement(t)]));
  const stmts = FILES.map(([, f], i) => ({ name: `s${i}`, ...parsed[f] }));
  const TODAY = "2026-10-01";
  const installed = ["Norton 360", "AnyDesk", "7-Zip 24.08"];
  const scenarios = {
    plain: { merchants: "test", today: TODAY },
    cancels: { merchants: "test", today: TODAY, cancels: [{ merchant: "netflix", on: "2026-08-05" }, { merchant: "spotify", on: "2026-07-10" }, { merchant: "adobe", on: "2026-09-20" }] },
    incident: { merchants: "test", today: TODAY, incidentDate: "2026-08-14" },
    installed: { merchants: "test", today: TODAY, installed },
    shipped: { merchants: "shipped", today: TODAY, incidentDate: "2026-08-14", installed },
  };
  const analyses = Object.fromEntries(Object.entries(scenarios).map(([k, o]) => [k, analyze(stmts, { ...o, merchants: o.merchants === "test" ? DIR : loadMerchants() })]));
  const real = loadMerchants();
  const descriptors = stmts.flatMap((s) => s.rows.map((r) => r.descriptor));
  const samples = ["$1,234.56", "(15.99)", "15.99-", "USD 9.99", "abc", "", "-(5.00)", "+3.10", "1,000", "12.345", "€ 4,20", "09/01/2026", "9/1/26", "2026-09-01", "Sep 1, 2026", "01 Sep 2026", "02/30/2026", "hello", "1-2-26", "31 Dec 99",
    "Zelle Conf# 5829301746", "card 4111 1111 1111 1111 x", "SHELL OIL 57444", "Payment Thank You-Mobile", "CHECKCARD GOOGLE *PLAY GIFT CARD", "WISE TRANSFER", "CHECK #1234", "NETFLIX.COM"];
  const golden = {
    note: "Generated by rust/tools/money-golden.mjs from app/src/money/*.mjs. Do not edit by hand.",
    parsed, analyses,
    helpers: samples.map((s) => ({ s, amount: parseAmount(s), date: parseDate(s), mask: maskDigits(s), kind: classify(s) })),
    directory: {
      cancelUrls: real.map((m) => ({ provider: m.provider, url: safeCancelUrl(m) })),
      testCancelUrls: DIR.map((m) => ({ provider: m.provider, url: safeCancelUrl(m) })),
      matches: descriptors.map((d) => { const m = matchMerchant(d, real); return { d, provider: m?.merchant.provider ?? null, ambiguous: m?.ambiguous ?? null, key: merchantKey(d) }; }),
    },
  };
  void strip;
  fs.writeFileSync(GOLDEN, JSON.stringify(golden, null, 1));
  console.log("wrote", GOLDEN, Object.keys(golden.analyses).length, "scenarios");
} else if (mode === "parse") {
  const [inFile, outFile] = process.argv.slice(3);
  const out = fs.createWriteStream(outFile);
  const rl = readline.createInterface({ input: fs.createReadStream(inFile), crlfDelay: Infinity });
  for await (const line of rl) {
    if (!line.trim()) continue;
    const { id, text } = JSON.parse(line);
    let r;
    try { r = parseStatement(text); } catch (e) { r = { error: String(e && e.message || e) }; }
    out.write(JSON.stringify({ id, r }) + "\n");
  }
  out.end();
} else {
  console.error("usage: node rust/tools/money-golden.mjs extract | golden | parse <in.jsonl> <out.jsonl>");
  process.exit(2);
}
