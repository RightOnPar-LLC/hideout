// guide-golden.mjs - the guide's spec and redactor answers, from the JavaScript app itself,
// so the Rust port can be held to them exactly.
//
//   node rust/tools/guide-golden.mjs spec
//        write crates/hideout-guide/tests/spec-golden.json from app/src/guide-spec.mjs
//   node rust/tools/guide-golden.mjs redact <in.jsonl> <out.jsonl>
//        run makeRedactor({names, computer}).text(text) on every line (the differential run)
//
// Developer tool. Writes only crates/hideout-guide/tests/spec-golden.json and the path given.
import fs from "node:fs";
import path from "node:path";
import readline from "node:readline";
import { fileURLToPath } from "node:url";
import * as spec from "../../app/src/guide-spec.mjs";
import { makeRedactor } from "../../app/src/redact.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const mode = process.argv[2];

// Tool inputs to validate: every tool, good and bad, the edge cases the selftests use.
const ISO = ["2026-09-01", "2026-9-1", "", "last week", "2026-02-30", "20260901"];
const CASES = [];
for (const name of [...spec.GUIDE_TOOLS, "delete_file", "constructor", ""]) {
  CASES.push([name, {}], [name, null], [name, []], [name, "x"], [name, { x: 1 }]);
}
CASES.push(
  ["start_deep_check", { with_admin: true }], ["start_deep_check", { with_admin: false }], ["start_deep_check", { with_admin: "yes" }], ["start_deep_check", { with_admin: true, extra: 1 }],
  ["update_case_step", { step: "enabled_two_step", status: "done" }], ["update_case_step", { step: "enabled_two_step", status: "maybe" }], ["update_case_step", { step: "constructor", status: "done" }], ["update_case_step", { step: "toString", status: "done" }],
  ["update_case_step", { step: "contacted_bank", status: "not_applicable", note: "x" }], ["update_case_step", { status: "done" }],
  ["mark_canceled", { merchant: "netflix", canceled_on: "2026-08-05", x: 1 }], ["mark_canceled", { merchant: "a/b", canceled_on: "2026-08-05" }], ["mark_canceled", { merchant: "x".repeat(65), canceled_on: "2026-08-05" }], ["mark_canceled", { merchant: "x".repeat(64), canceled_on: "2026-08-05" }],
  ["show_cancel_steps", { merchant: "TECH SUPPORT" }], ["show_cancel_steps", { merchant: "" }], ["show_cancel_steps", { merchant: 5 }],
  ["offer_letter", { kind: "refund_request", subject: "s", body: "b", to: "scammer@evil.example" }], ["offer_letter", { kind: "refund_request", subject: "s", body: "b" }], ["offer_letter", { kind: "refund_request", merchant: "adobe", subject: "s", body: "b" }],
  ["offer_letter", { kind: "nope", subject: "s", body: "b" }], ["offer_letter", { kind: "bank_dispute", subject: "  ", body: "b" }], ["offer_letter", { kind: "bank_dispute", subject: "s".repeat(201), body: "b" }], ["offer_letter", { kind: "bank_dispute", subject: "s".repeat(200), body: "b".repeat(8000) }],
  ["offer_letter", { kind: "bank_dispute", subject: "s", body: "b".repeat(8001) }], ["offer_letter", { kind: "cancel_by_email", merchant: null, subject: "s", body: "b" }], ["offer_letter", { kind: "cancel_by_email", merchant: "bad id!", subject: "s", body: "b" }],
);
for (const d of ISO) CASES.push(["set_incident_date", { date: d }], ["mark_canceled", { merchant: "netflix", canceled_on: d }]);
CASES.push(["set_incident_date", { date: 20260901 }], ["set_incident_date", { date: "2026-09-01", extra: true }]);

if (mode === "spec") {
  const golden = {
    note: "Generated by rust/tools/guide-golden.mjs from app/src/guide-spec.mjs. Do not edit by hand.",
    MODEL: spec.MODEL, EFFORT: spec.EFFORT, MAX_TOKENS: spec.MAX_TOKENS, FALLBACK_BETA: spec.FALLBACK_BETA,
    CASE_STEPS: spec.CASE_STEPS, STEP_STATUS: spec.STEP_STATUS, LETTER_KINDS: spec.LETTER_KINDS, GUIDE_TOOLS: spec.GUIDE_TOOLS,
    requestParams: spec.requestParams([{ role: "user", content: "am I hacked?" }]),
    validate: CASES.map(([name, input]) => ({ name, input, result: spec.validateToolInput(name, input) })),
  };
  const out = path.join(HERE, "..", "crates", "hideout-guide", "tests", "spec-golden.json");
  fs.writeFileSync(out, JSON.stringify(golden, null, 1) + "\n");
  console.log(`wrote ${path.relative(process.cwd(), out)}: ${golden.validate.length} validation cases, ${golden.GUIDE_TOOLS.length} tools`);
} else if (mode === "redact") {
  const [inf, outf] = process.argv.slice(3);
  const out = fs.createWriteStream(outf);
  const cache = new Map();
  // Split on "\n" only: readline also breaks lines at U+2028/U+2029, which the
  // differential's texts contain on purpose (JSON leaves them unescaped).
  for (const line of fs.readFileSync(inf, "utf8").split("\n")) {
    if (!line.trim()) continue;
    const { id, names, computer, text } = JSON.parse(line);
    const key = JSON.stringify([names, computer]);
    if (!cache.has(key)) cache.set(key, makeRedactor({ names, computer }));
    out.write(JSON.stringify({ id, r: cache.get(key).text(text) }) + "\n");
  }
  out.end();
} else {
  console.error("usage: node rust/tools/guide-golden.mjs spec | redact <in.jsonl> <out.jsonl>");
  process.exit(2);
}
